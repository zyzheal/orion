		if err != nil {
			log.Printf("ERROR parse %s: %v", f, err)
			errors++
			continue
		}
		if len(methods) == 0 {
			skipped++
			continue
		}

		outPath := filepath.Join(filepath.Dir(f), "service_interface.go")
		if _, err := os.Stat(outPath); err == nil {
			skipped++
			continue
		}

