package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"sort"
	"strings"
	"text/template"
)

const interfaceTmpl = `// Code generated by tools/generate_service_interface.go. DO NOT EDIT.
package service

type ServiceInterface interface {
{{ range .Methods }}	{{ . }}
{{ end }}
}

var _ ServiceInterface = (*Service)(nil)
`

func main() {
	path := "/Users/heal/orion-design/orion-platform-svc-go/internal/build/service/service.go"
	methods, err := extractPublicMethods(path)
	if err != nil {
		fmt.Printf("Error: %v\n", err)
		return
	}
	fmt.Printf("Methods (%d):\n", len(methods))
	for _, m := range methods {
		fmt.Printf("  |%s|\n", m)
	}

	data := struct{ Methods []string }{Methods: methods}
	tmpl := template.Must(template.New("x").Parse(interfaceTmpl))
	var buf bytes.Buffer
	tmpl.Execute(&buf, data)
	fmt.Printf("\n--- OUTPUT ---\n%s\n", buf.String())
}

func extractPublicMethods(path string) ([]string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse: %w", err)
	}

	var methods []string
	methodsSeen := make(map[string]bool)
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}
		recv := fn.Recv.List[0]
		var recvTypeName string
		switch e := recv.Type.(type) {
		case *ast.StarExpr:
			recvTypeName = typeName(e.X)
		case *ast.Ident:
			recvTypeName = e.Name
		}
		if recvTypeName != "Service" {
			continue
		}
		name := fn.Name.Name
		if !ast.IsExported(name) {
			continue
		}
		if methodsSeen[name] {
			continue
		}
		methodsSeen[name] = true
		sig := buildMethodSignature(fn)
		methods = append(methods, sig)
	}
	sort.Strings(methods)
	return methods, nil
}

func buildMethodSignature(fn *ast.FuncDecl) string {
	params := fmtParamList(fn.Type.Params)
	results := fmtParamList(fn.Type.Results)
	return fmt.Sprintf("%s%s%s", fn.Name.Name, params, results)
}

func fmtParamList(fields *ast.FieldList) string {
	if fields == nil {
		return ""
	}
	if fields.NumFields() == 0 {
		return ""
	}
	// Single unnamed result (e.g., "(error)")
	if fields.NumFields() == 1 && fields.List[0].Names == nil {
		return " " + typeToString(fields.List[0].Type)
	}

	parts := make([]string, 0, fields.NumFields())
	for _, f := range fields.List {
		if len(f.Names) > 0 {
			names := make([]string, len(f.Names))
			for j, n := range f.Names {
				names[j] = n.Name
			}
			types := typeToString(f.Type)
			if len(names) == 1 {
				parts = append(parts, fmt.Sprintf("%s %s", names[0], types))
			} else {
				parts = append(parts, fmt.Sprintf("%s %s", strings.Join(names, ", "), types))
			}
		} else {
			parts = append(parts, typeToString(f.Type))
		}
	}

	// Return " (param1 type, param2 type)"
	return "(" + strings.Join(parts, ", ") + ")"
}

func typeToString(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.StarExpr:
		return "*" + typeToString(e.X)
	case *ast.ArrayType:
		return "[]" + typeToString(e.Elt)
	case *ast.MapType:
		return fmt.Sprintf("map[%s]%s", typeToString(e.Key), typeToString(e.Value))
	case *ast.ChanType:
		dir := ""
		switch e.Dir {
		case ast.SEND:
			dir = "<-chan "
		case ast.RECV:
			_ = dir
			dir = "chan<- "
		default:
			dir = "chan "
		}
		return dir + typeToString(e.Value)
	case *ast.FuncType:
		params := fmtParamList(e.Params)
		results := fmtParamList(e.Results)
		return fmt.Sprintf("func%s%s", params, results)
	case *ast.Ellipsis:
		return "..." + typeToString(e.Elt)
	case *ast.SelectorExpr:
		return fmt.Sprintf("%s.%s", typeToString(e.X), e.Sel.Name)
	case *ast.IndexExpr:
		return fmt.Sprintf("%s[%s]", typeToString(e.X), typeToString(e.Index))
	case *ast.InterfaceType:
		return "any"
	case *ast.StructType:
		return "struct{}"
	default:
		return fmt.Sprintf("%T", expr)
	}
}

func typeName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		return e.Sel.Name
	default:
		return "any"
	}
}
