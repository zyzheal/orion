package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"
)

var rootDir = flag.String("root", "", "Root of orion-platform-svc-go")

const interfaceTmpl = `// Code generated by tools/generate_service_interface.go. DO NOT EDIT.
//
// This file defines the ServiceInterface for {{ .ModuleName }}.
// Generated to enable handler layer mocking in tests.

package service

{{ if .Imports -}}
import (
{{ range .Imports }}	{{ . }}
{{ end -}}
)
{{ end -}}
// ServiceInterface defines the interface for the {{ .ModuleName }} service.
type ServiceInterface interface {
{{ range .Methods }}	{{ . }}
{{ end }}
}

// Ensure compile-time safety: *Service implements ServiceInterface.
var _ ServiceInterface = (*Service)(nil)
`

func main() {
	flag.Parse()
	if *rootDir == "" {
		flag.Usage()
		os.Exit(1)
	}

	files, err := filepath.Glob(filepath.Join(*rootDir, "internal/*", "service", "service.go"))
	if err != nil {
		log.Fatalf("glob error: %v", err)
	}
	if len(files) == 0 {
		log.Fatalf("no service/service.go files found")
	}

	created := 0
	skipped := 0
	errors := 0

	for _, f := range files {
		modulePath := filepath.Dir(filepath.Dir(f))
		moduleNameFromPath := filepath.Base(modulePath)

		methods, imports, err := extractPublicMethods(f)
		if err != nil {
			log.Printf("ERROR parse %s: %v", f, err)
			errors++
			continue
		}
		if len(methods) == 0 {
			skipped++
			continue
		}

		outPath := filepath.Join(filepath.Dir(f), "service_interface.go")
		if _, err := os.Stat(outPath); err == nil {
			skipped++
			continue
		}

		data := struct {
			ModuleName string
			Methods    []string
			Imports    []string
		}{moduleNameFromPath, methods, imports}

		tmpl := template.Must(template.New("interface").Parse(interfaceTmpl))
		var buf bytes.Buffer
		if err := tmpl.Execute(&buf, data); err != nil {
			log.Printf("ERROR template %s: %v", outPath, err)
			errors++
			continue
		}

		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			os.WriteFile(outPath+".raw", buf.Bytes(), 0644)
			log.Printf("ERROR format %s: %v", outPath, err)
			errors++
			continue
		}

		if err := os.WriteFile(outPath, formatted, 0644); err != nil {
			log.Printf("ERROR write %s: %v", outPath, err)
			errors++
			continue
		}
		created++
	}

	log.Printf("Done. Created=%d Skipped=%d Errors=%d", created, skipped, errors)
}

func extractPublicMethods(path string) ([]string, []string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		return nil, nil, err
	}

	// Build import lookup: localName -> import spec string
	importLookup := make(map[string]string)
	for _, imp := range f.Imports {
		name := ""
		if imp.Name != nil {
			name = imp.Name.Name
		}
		pkgPath := strings.Trim(imp.Path.Value, "\"")
		var localName string
		if name != "" && name != "." {
			localName = name
		} else {
			localName = filepath.Base(pkgPath)
		}
		importLookup[localName] = fmt.Sprintf("\"%s\"", pkgPath)
	}

	var methods []string
	methodsSeen := make(map[string]bool)
	referencedPkgs := make(map[string]bool)

	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}

		recv := fn.Recv.List[0]
		var recvTypeName string
		switch e := recv.Type.(type) {
		case *ast.StarExpr:
			recvTypeName = typeName(e.X)
		case *ast.Ident:
			recvTypeName = e.Name
		}
		if recvTypeName != "Service" {
			continue
		}

		name := fn.Name.Name
		if !ast.IsExported(name) {
			continue
		}
		if methodsSeen[name] {
			continue
		}
		methodsSeen[name] = true

		params := fmtParamList(fn.Type.Params, &referencedPkgs, importLookup)
		results := fmtParamList(fn.Type.Results, &referencedPkgs, importLookup)
		methods = append(methods, fmt.Sprintf("%s%s%s", name, params, results))
	}

	var imports []string
	for pkg, spec := range importLookup {
		if referencedPkgs[pkg] {
			imports = append(imports, spec)
		}
	}
	sort.Strings(imports)

	sort.Strings(methods)
	return methods, imports, nil
}

func fmtParamList(fields *ast.FieldList, refPkgs *map[string]bool, importLookup map[string]string) string {
	if fields == nil || fields.NumFields() == 0 {
		return ""
	}

	parts := make([]string, 0, fields.NumFields())
	for _, f := range fields.List {
		if len(f.Names) > 0 {
			names := make([]string, len(f.Names))
			for j, n := range f.Names {
				names[j] = n.Name
			}
			types := typeToString(f.Type, refPkgs, importLookup)
			if len(names) == 1 {
				parts = append(parts, fmt.Sprintf("%s %s", names[0], types))
			} else {
				parts = append(parts, fmt.Sprintf("%s %s", strings.Join(names, ", "), types))
			}
		} else {
			types := typeToString(f.Type, refPkgs, importLookup)
			parts = append(parts, types)
		}
	}

	return "(" + strings.Join(parts, ", ") + ")"
}

func typeToString(expr ast.Expr, refPkgs *map[string]bool, importLookup map[string]string) string {
	switch e := expr.(type) {
	case *ast.Ident:
		name := e.Name
		if _, ok := importLookup[name]; ok {
			(*refPkgs)[name] = true
		}
		return name
	case *ast.StarExpr:
		return "*" + typeToString(e.X, refPkgs, importLookup)
	case *ast.ArrayType:
		return "[]" + typeToString(e.Elt, refPkgs, importLookup)
	case *ast.MapType:
		return fmt.Sprintf("map[%s]%s", typeToString(e.Key, refPkgs, importLookup), typeToString(e.Value, refPkgs, importLookup))
	case *ast.ChanType:
		dir := "chan "
		if e.Dir == ast.SEND {
			dir = "<-chan "
		} else if e.Dir == ast.RECV {
			dir = "chan<- "
		}
		return dir + typeToString(e.Value, refPkgs, importLookup)
	case *ast.FuncType:
		params := fmtParamList(e.Params, refPkgs, importLookup)
		results := fmtParamList(e.Results, refPkgs, importLookup)
		return fmt.Sprintf("func%s%s", params, results)
	case *ast.Ellipsis:
		return "..." + typeToString(e.Elt, refPkgs, importLookup)
	case *ast.SelectorExpr:
		if ident, ok := e.X.(*ast.Ident); ok {
			if _, ok := importLookup[ident.Name]; ok {
				(*refPkgs)[ident.Name] = true
			}
		}
		return fmt.Sprintf("%s.%s", typeToString(e.X, refPkgs, importLookup), e.Sel.Name)
	case *ast.IndexExpr:
		return fmt.Sprintf("%s[%s]", typeToString(e.X, refPkgs, importLookup), typeToString(e.Index, refPkgs, importLookup))
	case *ast.InterfaceType:
		return "any"
	case *ast.StructType:
		return "struct{}"
	default:
		return fmt.Sprintf("%T", expr)
	}
}

func typeName(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		return e.Sel.Name
	}
	return "any"
}
