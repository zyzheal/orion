package main

import (
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type method struct {
	name string
}

func main() {
	root := "internal"
	matches, _ := filepath.Glob(filepath.Join(root, "**/repository/repository.go"))

	for _, path := range matches {
		outPath := strings.Replace(path, "repository.go", "repository_interface.go", 1)
		if _, err := os.Stat(outPath); err == nil {
			println("SKIP_EXISTS", outPath)
			continue
		}
		if err := generateInterface(path, outPath); err != nil {
			println("ERROR", path, ":", err.Error())
		} else {
			println("OK", outPath)
		}
	}
}

func generateInterface(path, outPath string) error {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return err
	}

	methods := collectPublicMethods(file)
	if len(methods) == 0 {
		println("SKIP_NO_METHODS", path)
		return nil
	}

	sort.Slice(methods, func(i, j int) bool {
		return methods[i].name < methods[j].name
	})

	content := buildContent(file, methods, path)
	return os.WriteFile(outPath, []byte(content), 0644)
}

func collectPublicMethods(file *ast.File) []method {
	var result []method
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Body == nil || fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}
		recv := fn.Recv.List[0]
		recvType, ok := recv.Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		id, ok := recvType.X.(*ast.Ident)
		if !ok || id.Name != "Repository" {
			continue
		}
		if fn.Name.Name[0] < 'A' || fn.Name.Name[0] > 'Z' {
			continue
		}
		result = append(result, method{name: fn.Name.Name})
	}
	return result
}

func buildContent(file *ast.File, methods []method, srcPath string) string {
	modelsImport := ""
	for _, imp := range file.Imports {
		if imp.Name != nil && imp.Name.Name == "models" {
			modelsImport = strings.Trim(imp.Path.Value, "\"")
		}
		if strings.HasSuffix(imp.Path.Value, "\"models\"") {
			modelsImport = strings.Trim(imp.Path.Value, "\"")
		}
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by tools/gen-interface/main.go. DO NOT EDIT.\n")
	sb.WriteString("package repository\n\n")
	sb.WriteString("import (\n")
	sb.WriteString("\t\"context\"\n")
	if modelsImport != "" {
		"have_models"
		sb.WriteString("\t\"" + modelsImport + "\"\n")
	}
	sb.WriteString(")\n\n")

	sb.WriteString("type Repository interface {\n")
	for _, m := range methods {
		sig := findSignature(file, m.name)
		sb.WriteString(sig + "\n")
	}
	sb.WriteString("}\n")
	return sb.String()
}

func findSignature(file *ast.File, name string) string {
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != name {
			continue
		}
		if fn.Recv == nil || len(fn.Recv.List) == 0 {
			continue
		}
		recvType, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		id, ok := recvType.X.(*ast.Ident)
		if !ok || id.Name != "Repository" {
			continue
		}
		var sb strings.Builder
		sb.WriteString("\t" + name + "(")
		if fn.Type.Params != nil && len(fn.Type.Params.List) > 0 {
			params := formatFields(fn.Type.Params.List)
			sb.WriteString(params)
		}
		if fn.Type.Results != nil && len(fn.Type.Results.List) > 0 {
			sb.WriteString(") " + formatFields(fn.Type.Results.List))
		} else {
			sb.WriteString(")")
		}
		return sb.String()
	}
	return ""
}

func formatFields(fields []*ast.Field) string {
	if len(fields) == 0 {
		return ""
	}
	parts := make([]string, 0, len(fields))
	for _, f := range fields {
		name := ""
		for j, n := range f.Names {
			if j > 0 {
				name += " "
			}
			name += n.Name
		}
		if name != "" {
			name += " "
		}
		typ := astToString(f.Type)
		parts = append(parts, name+typ)
	}
	return strings.Join(parts, ", ")
}

func astToString(expr ast.Expr) string {
	var buf strings.Builder
	printer.Fprint(&buf, token.NewFileSet(), expr)
	return buf.String()
}

