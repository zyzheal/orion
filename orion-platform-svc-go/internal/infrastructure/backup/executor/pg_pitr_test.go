func TestBuildPGRecoveryScript_AllStepsCommented(t *testing.T) {
	s := buildPGRecoveryScript(PGRecoveryPlan{
		BackupID:   "b-1",
		BackupPath: "/var/backups/base.dump",
		ArchiveDir: "/var/lib/orion-pitr/pitr-b-1",
		ArchiveFiles: []ArchiveFileInfo{
			{Path: "/x/seg1", SHA256: "abc"},
		},
		GeneratedAt: time.Date(2026, 7, 1, 0, 0, 0, 0, time.UTC),
	})
	// All DB-mutating commands must be commented.
	for _, cmd := range []string{"pg_restore", "pg_ctl", "restore_command", "recovery_target_inclusive"} {
		if idx := strings.Index(s, cmd); idx < 0 {
			t.Fatalf("missing %s in script", cmd)
		} else {
			line := extractLine(idx, s)
			trimmed := strings.TrimSpace(line)
			if !strings.HasPrefix(trimmed, "#") {
				t.Fatalf("command %s not commented: %q", cmd, line)
			}
		}
	}
}

func TestCopyFile_CopiesAndSetsMode(t *testing.T) {
	src := filepath.Join(t.TempDir(), "src")
	if err := os.WriteFile(src, []byte("hello"), 0o644); err != nil {
		t.Fatal(err)
	}
	dst := filepath.Join(t.TempDir(), "dst")
	if err := copyFile(src, dst); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(dst)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != "hello" {
		t.Fatalf("content mismatch %q", got)
	}
	fi, err := os.Stat(dst)
	if err != nil {
		t.Fatal(err)
	}
	if fi.Mode().Perm() != 0o600 {
		t.Fatalf("expected 0600 perms, got %v", fi.Mode().Perm())
	}
}

