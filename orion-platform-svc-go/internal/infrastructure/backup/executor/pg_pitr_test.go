func TestPreparePGRecoveryPlan_EmptyArchivesOK(t *testing.T) {
	scratch := t.TempDir()
	plan, err := PreparePGRecoveryPlan(context.Background(), PGRecoveryOptions{
		BackupID:   "b-empty",
		BackupPath: "/var/backups/base.dump",
		ScratchDir: scratch,
	}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if plan == nil {
		t.Fatal("expected non-nil plan")
	}
	if plan.BackupID != "b-empty" {
		t.Fatalf("backup id mismatch %q", plan.BackupID)
	}
	if plan.ManifestSHA256 == "" {
		t.Fatal("manifest sha256 must be set")
	}
	if plan.ScriptPath == "" || !fileExists(plan.ScriptPath) {
		t.Fatalf("script not written: %q", plan.ScriptPath)
	}
	script, err := os.ReadFile(plan.ScriptPath)
	if err != nil {
		t.Fatal(err)
	}
	s := string(script)
	if !strings.HasPrefix(s, "#!/usr/bin/env bash") {
		t.Fatalf("script missing shebang: %q", s[:min(30, len(s))])
	}
	if !strings.Contains(s, "set -euo pipefail") {
		t.Fatal("script missing set -euo pipefail")
	}
	if !strings.Contains(s, "Auto-generated by orion-platform-svc") {
		t.Fatal("script missing generated-by header")
	}
}

func TestPreparePGRecoveryPlan_CopiesAndHashesArchives(t *testing.T) {
	scratch := t.TempDir()
	srcDir := t.TempDir()
	src1 := filepath.Join(srcDir, "000000010000000000000001")
	src2 := filepath.Join(srcDir, "000000010000000000000002")
	content1 := []byte("wal-segment-1")
	content2 := []byte("wal-segment-2")
	if err := os.WriteFile(src1, content1, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(src2, content2, 0o600); err != nil {
		t.Fatal(err)
	}

	plan, err := PreparePGRecoveryPlan(context.Background(), PGRecoveryOptions{
		BackupID:     "b-hash",
		BackupPath:   "/var/backups/base.dump",
		ArchivePaths: []string{src1, src2},
		ScratchDir:   scratch,
	}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(plan.ArchiveFiles) != 2 {
		t.Fatalf("expected 2 archive files, got %d", len(plan.ArchiveFiles))
	}
	// Verify the copied file contents and that the SHA256 matches.
	for _, af := range plan.ArchiveFiles {
		if !fileExists(af.Path) {
			t.Fatalf("archive copy missing: %s", af.Path)
		}
		got, err := os.ReadFile(af.Path)
		if err != nil {
			t.Fatal(err)
		}
		sum := sha256.Sum256(got)
		if hex.EncodeToString(sum[:]) != af.SHA256 {
			t.Fatalf("sha mismatch for %s: %s vs %s", af.Path, af.SHA256, hex.EncodeToString(sum[:]))
		}
	}
	script, err := os.ReadFile(plan.ScriptPath)
	if err != nil {
		t.Fatal(err)
	}
	s := string(script)
	for _, af := range plan.ArchiveFiles {
		if !strings.Contains(s, af.Path) {
			t.Fatalf("script missing path %s", af.Path)
		}
		if !strings.Contains(s, af.SHA256) {
			t.Fatalf("script missing sha %s", af.SHA256)
		}
	}
}

