func TestHashString_Deterministic(t *testing.T) {
	a := hashString("abc")
	b := hashString("abc")
	if a != b {
		t.Fatalf("hashString not deterministic: %s vs %s", a, b)
	}
	c := hashString("abd")
	if c == a {
		t.Fatal("different inputs produced same hash")
	}
	if len(a) != 64 {
		t.Fatalf("sha256 hex should be 64 chars, got %d", len(a))
	}
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func extractLine(idx int, s string) string {
	start := idx
	for start > 0 && s[start-1] != '\n' {
		start--
	}
	end := idx
	for end < len(s) && s[end] != '\n' {
		end++
	}
	return s[start:end]
}
